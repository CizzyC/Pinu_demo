def topic(title, children=None):
    item = {"id": uuid.uuid4().hex, "title": title}
    if children:
        attached = [topic(k, v) for k, v in children.items()]
        item["children"] = {"attached": attached}
    return item


def main():
    root_title, root_children = next(iter(mind.items()))
    content = [
        {
            "id": uuid.uuid4().hex,
            "class": "sheet",
            "title": root_title,
            "rootTopic": topic(root_title, root_children),
            "topicPositioning": "fixed",
            "extensions": [],
        }
    ]
    metadata = {
        "creator": {"name": "Codex", "version": "1.0"},
        "activeSheetId": content[0]["id"],
        "createdTime": int(time.time() * 1000),
        "modifiedTime": int(time.time() * 1000),
    }
    manifest = {
        "file-entries": {
            "content.json": {},
            "metadata.json": {},
        }
    }
    with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("content.json", json.dumps(content, ensure_ascii=False, indent=2))
        zf.writestr("metadata.json", json.dumps(metadata, ensure_ascii=False, indent=2))
        zf.writestr("manifest.json", json.dumps(manifest, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
